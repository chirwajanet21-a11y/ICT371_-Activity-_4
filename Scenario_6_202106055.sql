CREATE OR REPLACE PROCEDURE sc6_events.cancel_booking(p_booking_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item_id integer;
    v_qty     integer;
BEGIN
    SELECT event_id, seats
    INTO v_item_id, v_qty
    FROM sc6_events.bookings
    WHERE booking_id = p_booking_id AND status = 'CONFIRMED'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No confirmed booking with ID %', p_booking_id;
        RETURN;
    END IF;

    UPDATE sc6_events.bookings
    SET status = 'CANCELLED'
    WHERE booking_id = p_booking_id;

    UPDATE sc6_events.events
    SET available_seats = available_seats + v_qty
    WHERE event_id = v_item_id;

    RAISE NOTICE 'Booking % cancelled; % seats released', p_booking_id, v_qty;
END;
$$;

