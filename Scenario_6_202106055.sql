CREATE OR REPLACE PROCEDURE sc6_events.show_tight_events(p_threshold integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR (p_limit integer) FOR
        SELECT event_name, available_seats
        FROM sc6_events.events
        WHERE available_seats <= p_limit
        ORDER BY event_id;
BEGIN
    OPEN c_low(p_threshold);
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;           
        RAISE NOTICE 'Full or nearly full: "%" (% seats left)', v_item.event_name, v_item.available_seats;
    END LOOP;
    CLOSE c_low;
END;
$$;

